<h1 class="text-bordeaux">Conditions générales de vente</h1>

<h2 class="h4">1. Commande</h2>
<p>Les commandes se font sur le site après création d'un compte. Chaque menu a un nombre minimum de personnes
et des conditions (délai de commande, conservation) affichées sur la page du menu.</p>

<h2 class="h4">2. Prix</h2>
<p>Les prix sont indiqués en euros TTC. Une réduction de 10% est appliquée si la commande compte au moins
5 personnes de plus que le minimum du menu.</p>

<h2 class="h4">3. Livraison</h2>
<p>La livraison est gratuite dans la ville de Bordeaux. En dehors de Bordeaux, elle est facturée 5 € plus 0,59 € par kilomètre.</p>

<h2 class="h4">4. Annulation et modification</h2>
<p>Le client peut annuler ou modifier sa commande depuis son espace tant qu'elle n'a pas été acceptée par notre équipe.</p>

<h2 class="h4">5. Prêt de matériel</h2>
<p>Pour certains menus, du matériel peut être prêté. Il doit être rendu dans un délai de 10 jours ouvrés après
la prestation. Passé ce délai, des frais de <strong>600 €</strong> seront facturés au client.
Pour rendre le matériel, le client doit contacter la société.</p>

